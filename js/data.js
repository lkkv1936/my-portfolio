/** Flat list for search */
export function getSearchIndex() {
  const fromWorks = works.map((w) => ({
    title: w.title,
    href: w.link || '#works',
    type: 'Work',
    keywords: [w.title, w.description, ...(w.tags || [])].join(' ').toLowerCase(),
  }));
  const fromIllus = illustrations.map((i) => ({
    title: i.title,
    href: '#illustrations',
    type: 'Illustration',
    keywords: [i.title, i.description, ...(i.tags || [])].join(' ').toLowerCase(),
  }));
  const fromCats = featuredCategories.map((c) => ({
    title: c.title,
    href: c.href,
    type: 'Category',
    keywords: c.title.toLowerCase(),
  }));
  return [...fromWorks, ...fromIllus, ...fromCats];
}
